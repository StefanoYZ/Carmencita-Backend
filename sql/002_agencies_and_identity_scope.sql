CREATE TABLE IF NOT EXISTS agencies (
    agency_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_code VARCHAR(30) NOT NULL UNIQUE,
    district VARCHAR(50) NOT NULL,
    province VARCHAR(50),
    department VARCHAR(50),
    address VARCHAR(100),
    phone VARCHAR(15) NOT NULL,
    status VARCHAR(15) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_agencies_code CHECK (agency_code ~ '^AG_[A-Z0-9_]+$'),
    CONSTRAINT ck_agencies_status CHECK (status IN ('ACTIVA', 'INACTIVA'))
);

ALTER TABLE roles DROP CONSTRAINT IF EXISTS ck_roles_name;
ALTER TABLE roles
    ADD CONSTRAINT ck_roles_name
    CHECK (role_name IN ('ADMIN', 'AGENCY_ADMIN', 'SECRETARY', 'LOADER', 'DRIVER'));

ALTER TABLE internal_users
    ADD COLUMN IF NOT EXISTS agency_id SMALLINT REFERENCES agencies(agency_id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS ix_internal_users_agency_id ON internal_users (agency_id);

CREATE TABLE IF NOT EXISTS agency_admin_assignments (
    agency_id SMALLINT PRIMARY KEY REFERENCES agencies(agency_id) ON DELETE RESTRICT,
    user_id INTEGER NOT NULL UNIQUE REFERENCES internal_users(user_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id INTEGER REFERENCES internal_users(user_id) ON DELETE SET NULL
);
